/** Icon sizes: 16 inline (default), 20 buttons/headers, 24 popup titles. Stroke is always 1.5. */
export function Icon({ name, size = 16, label }: { name: IconName; size?: 16 | 20 | 24; label?: string }) {
  const C = ICONS[name];
  return (
    <C
      width={size}
      height={size}
      style={{
        width: `calc(${size}px * var(--icon-scale, 1))`,
        height: `calc(${size}px * var(--icon-scale, 1))`,
      }}
      strokeWidth={1.5}
      className="icon"
      aria-hidden={label ? undefined : true}
      aria-label={label}
      role={label ? "img" : undefined}
    />
  );
}
